CREATE OR REPLACE FUNCTION public.actualizar_estado_pedido(
  p_actor_id UUID,
  p_pedido_id UUID,
  p_estado TEXT,
  p_motivo TEXT DEFAULT NULL
)
RETURNS public.pedidos
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pedido public.pedidos;
  v_estado_anterior TEXT;
  v_actor_role TEXT;
  v_actor_type TEXT;
  v_allowed BOOLEAN := FALSE;
BEGIN
  SELECT * INTO v_pedido FROM public.pedidos WHERE id = p_pedido_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pedido no encontrado'; END IF;

  SELECT role INTO v_actor_role FROM public.profiles WHERE id = p_actor_id;
  v_actor_type := CASE WHEN v_actor_role IN ('admin', 'super_admin') THEN 'admin'
    WHEN v_pedido.cliente_id = p_actor_id THEN 'cliente' ELSE 'comercio' END;

  IF NOT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = p_actor_id AND account_status = 'activo'
  ) THEN
    RAISE EXCEPTION 'La cuenta no esta activa';
  END IF;

  v_allowed := public.is_admin(p_actor_id)
    OR public.is_comercio_member(p_actor_id, v_pedido.comercio_id, ARRAY['owner', 'manager', 'atencion'])
    OR (v_pedido.cliente_id = p_actor_id AND p_estado = 'cancelado' AND v_pedido.estado = 'solicitado');
  IF NOT v_allowed THEN RAISE EXCEPTION 'No autorizado'; END IF;

  IF p_estado NOT IN ('aceptado', 'rechazado', 'preparando', 'listo', 'en_camino', 'entregado', 'cancelado') THEN
    RAISE EXCEPTION 'Estado invalido';
  END IF;

  v_estado_anterior := v_pedido.estado;
  IF NOT (
    (v_estado_anterior = 'solicitado' AND p_estado IN ('aceptado', 'rechazado', 'cancelado'))
    OR (v_estado_anterior = 'aceptado' AND p_estado IN ('preparando', 'cancelado'))
    OR (v_estado_anterior = 'preparando' AND p_estado IN ('listo', 'cancelado'))
    OR (v_estado_anterior = 'listo' AND (
      p_estado = 'entregado'
      OR (v_pedido.modalidad = 'domicilio' AND p_estado = 'en_camino')
    ))
    OR (v_estado_anterior = 'en_camino' AND p_estado = 'entregado')
  ) THEN
    RAISE EXCEPTION 'Transicion de pedido no permitida';
  END IF;

  IF p_estado IN ('cancelado', 'rechazado') AND length(trim(coalesce(p_motivo, ''))) < 3 THEN
    RAISE EXCEPTION 'Indique un motivo para cancelar o rechazar el pedido';
  END IF;

  UPDATE public.pedidos SET
    estado = p_estado,
    aceptado_at = CASE WHEN p_estado = 'aceptado' THEN NOW() ELSE aceptado_at END,
    completado_at = CASE WHEN p_estado = 'entregado' THEN NOW() ELSE completado_at END,
    cancelado_at = CASE WHEN p_estado IN ('cancelado', 'rechazado') THEN NOW() ELSE cancelado_at END,
    cancelado_por = CASE WHEN p_estado IN ('cancelado', 'rechazado') THEN p_actor_id ELSE cancelado_por END,
    motivo_cancelacion = CASE WHEN p_estado IN ('cancelado', 'rechazado') THEN NULLIF(p_motivo, '') ELSE motivo_cancelacion END,
    updated_at = NOW()
  WHERE id = p_pedido_id
  RETURNING * INTO v_pedido;

  IF p_estado IN ('cancelado', 'rechazado') THEN
    UPDATE public.productos producto
    SET stock = producto.stock + item.cantidad
    FROM public.pedido_items item
    WHERE item.pedido_id = p_pedido_id
      AND item.producto_id = producto.id
      AND producto.stock IS NOT NULL;
  END IF;

  INSERT INTO public.pedido_eventos (
    pedido_id, actor_id, actor_tipo, evento, estado_anterior, estado_nuevo, detalle
  ) VALUES (
    p_pedido_id, p_actor_id, v_actor_type, 'estado_actualizado',
    v_estado_anterior, p_estado,
    jsonb_build_object('motivo', p_motivo)
  );

  INSERT INTO public.audit_events (actor_id, action, resource_type, resource_id, before_data, after_data)
  VALUES (
    p_actor_id,
    'order.status_changed',
    'pedido',
    p_pedido_id::TEXT,
    jsonb_build_object('estado', v_estado_anterior),
    jsonb_build_object('estado', p_estado, 'motivo', p_motivo)
  );

  RETURN v_pedido;
END;
$$;

REVOKE ALL ON FUNCTION public.actualizar_estado_pedido(UUID, UUID, TEXT, TEXT)
