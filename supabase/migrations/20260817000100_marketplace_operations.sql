CREATE OR REPLACE FUNCTION public.consume_rate_limit(
  p_key_hash TEXT,
  p_limit INT,
  p_window_seconds INT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_window_start TIMESTAMPTZ;
  v_hits INT;
BEGIN
  IF p_limit <= 0 OR p_window_seconds <= 0 THEN
    RAISE EXCEPTION 'Invalid rate limit configuration';
  END IF;

  v_window_start := to_timestamp(floor(extract(epoch FROM NOW()) / p_window_seconds) * p_window_seconds);

  INSERT INTO public.api_rate_limit_windows (key_hash, window_start, hits)
  VALUES (p_key_hash, v_window_start, 1)
  ON CONFLICT (key_hash, window_start)
  DO UPDATE SET hits = public.api_rate_limit_windows.hits + 1, updated_at = NOW()
  RETURNING hits INTO v_hits;

  DELETE FROM public.api_rate_limit_windows
  WHERE window_start < NOW() - INTERVAL '2 days';

  RETURN v_hits <= p_limit;
END;
$$;

REVOKE ALL ON FUNCTION public.consume_rate_limit(TEXT, INT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_rate_limit(TEXT, INT, INT) TO service_role;

CREATE OR REPLACE FUNCTION public.create_pedido(
  p_cliente_id UUID,
  p_comercio_id UUID,
  p_modalidad TEXT,
  p_contacto_nombre TEXT,
  p_contacto_telefono TEXT,
  p_direccion_entrega JSONB,
  p_notas_cliente TEXT,
  p_items JSONB
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pedido_id UUID;
  v_item JSONB;
  v_producto RECORD;
  v_cantidad INT;
  v_precio NUMERIC(12,2);
  v_subtotal NUMERIC(12,2) := 0;
  v_producto_ids UUID[] := ARRAY[]::UUID[];
BEGIN
  IF p_modalidad NOT IN ('recoger', 'domicilio') THEN
    RAISE EXCEPTION 'Modalidad invalida';
  END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'El pedido requiere al menos un producto';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = p_cliente_id AND account_status = 'activo'
  ) THEN
    RAISE EXCEPTION 'La cuenta del cliente no esta activa';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.comercios
    WHERE id = p_comercio_id
      AND estado = 'activo'
      AND deleted_at IS NULL
      AND (
        (p_modalidad = 'recoger' AND recogida_disponible = TRUE)
        OR (p_modalidad = 'domicilio' AND domicilio_disponible = TRUE)
      )
  ) THEN
    RAISE EXCEPTION 'El comercio no esta disponible para esta modalidad';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_cantidad := COALESCE((v_item->>'cantidad')::INT, 0);
    IF v_cantidad <= 0 OR v_cantidad > 99 THEN
      RAISE EXCEPTION 'Cantidad invalida';
    END IF;
    IF (v_item->>'producto_id') IS NULL THEN
      RAISE EXCEPTION 'Producto invalido';
    END IF;
    IF (v_item->>'producto_id')::UUID = ANY(v_producto_ids) THEN
      RAISE EXCEPTION 'No se permite repetir un producto en el pedido';
    END IF;
    v_producto_ids := array_append(v_producto_ids, (v_item->>'producto_id')::UUID);

    SELECT id, nombre, sku, imagen_url, precio_base, precio_oferta, disponible, stock
    INTO v_producto
    FROM public.productos
    WHERE id = (v_item->>'producto_id')::UUID
      AND comercio_id = p_comercio_id
      AND deleted_at IS NULL
    FOR UPDATE;

    IF NOT FOUND OR v_producto.disponible IS NOT TRUE THEN
      RAISE EXCEPTION 'Producto no disponible';
    END IF;
    IF v_producto.stock IS NOT NULL AND v_producto.stock < v_cantidad THEN
      RAISE EXCEPTION 'Stock insuficiente';
    END IF;

    v_precio := COALESCE(v_producto.precio_oferta, v_producto.precio_base);
    v_subtotal := v_subtotal + (v_precio * v_cantidad);
  END LOOP;

  INSERT INTO public.pedidos (
    cliente_id, comercio_id, modalidad, contacto_nombre, contacto_telefono,
    direccion_entrega, notas_cliente, subtotal, costo_domicilio, total
  ) VALUES (
    p_cliente_id, p_comercio_id, p_modalidad, p_contacto_nombre, p_contacto_telefono,
    CASE WHEN p_modalidad = 'domicilio' THEN p_direccion_entrega ELSE NULL END,
    NULLIF(p_notas_cliente, ''), v_subtotal, 0, v_subtotal
  ) RETURNING id INTO v_pedido_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_cantidad := (v_item->>'cantidad')::INT;
    SELECT id, nombre, sku, imagen_url, precio_base, precio_oferta, stock
    INTO v_producto
    FROM public.productos
    WHERE id = (v_item->>'producto_id')::UUID;
    v_precio := COALESCE(v_producto.precio_oferta, v_producto.precio_base);

    INSERT INTO public.pedido_items (
      pedido_id, producto_id, nombre_producto, sku, imagen_url, precio_unitario, cantidad, total_linea
    ) VALUES (
      v_pedido_id, v_producto.id, v_producto.nombre, v_producto.sku, v_producto.imagen_url,
      v_precio, v_cantidad, v_precio * v_cantidad
    );

    IF v_producto.stock IS NOT NULL THEN
      UPDATE public.productos SET stock = stock - v_cantidad WHERE id = v_producto.id;
    END IF;
  END LOOP;

  INSERT INTO public.pedido_eventos (pedido_id, actor_id, actor_tipo, evento, estado_nuevo)
  VALUES (v_pedido_id, p_cliente_id, 'cliente', 'pedido_creado', 'solicitado');

  INSERT INTO public.audit_events (actor_id, action, resource_type, resource_id, after_data)
  VALUES (
    p_cliente_id,
    'order.created',
    'pedido',
    v_pedido_id::TEXT,
    jsonb_build_object('comercio_id', p_comercio_id, 'modalidad', p_modalidad, 'items', jsonb_array_length(p_items))
  );

  RETURN v_pedido_id;
END;
$$;

REVOKE ALL ON FUNCTION public.create_pedido(UUID, UUID, TEXT, TEXT, TEXT, JSONB, TEXT, JSONB)
