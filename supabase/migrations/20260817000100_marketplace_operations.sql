CREATE OR REPLACE FUNCTION public.is_comercio_member(
  p_user_id UUID,
  p_comercio_id UUID,
  p_roles TEXT[] DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.is_comercio_owner(p_user_id, p_comercio_id)
    OR EXISTS (
      SELECT 1
      FROM public.comercio_miembros cm
      WHERE cm.comercio_id = p_comercio_id
        AND cm.profile_id = p_user_id
        AND cm.activo = TRUE
        AND (p_roles IS NULL OR cm.rol = ANY(p_roles))
    )
$$;
