  moneda_codigo CHAR(3) NOT NULL DEFAULT 'COP',
  lat NUMERIC(9,6),
  lng NUMERIC(9,6),
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
