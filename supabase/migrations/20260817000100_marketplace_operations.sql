CREATE TABLE IF NOT EXISTS public.pedidos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  numero BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  cliente_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  comercio_id UUID NOT NULL REFERENCES public.comercios(id) ON DELETE RESTRICT,
  estado TEXT NOT NULL DEFAULT 'solicitado' CHECK (estado IN (
    'solicitado', 'aceptado', 'rechazado', 'preparando', 'listo',
    'en_camino', 'entregado', 'cancelado'
  )),
  modalidad TEXT NOT NULL CHECK (modalidad IN ('recoger', 'domicilio')),
  contacto_nombre TEXT NOT NULL,
  contacto_telefono TEXT NOT NULL,
  direccion_entrega JSONB,
  notas_cliente TEXT,
  subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
  costo_domicilio NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (costo_domicilio >= 0),
  total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
  solicitado_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aceptado_at TIMESTAMPTZ,
  completado_at TIMESTAMPTZ,
  cancelado_at TIMESTAMPTZ,
  cancelado_por UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  motivo_cancelacion TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pedidos_cliente_fecha ON public.pedidos(cliente_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_pedidos_comercio_estado ON public.pedidos(comercio_id, estado, created_at DESC);

